/** Composes shift/alpha like the firmware: four pages of 54 event codes. */
export class Modifiers {
  shift = false;
  alpha = false;
  lock = false;

  /** Returns the event for a key press and updates the modifier state. */
  press(k: number): number {
    if (k === 12) {
      this.shift = !this.shift;
      return 12;
    }
    if (k === 13) {
      if (this.shift) {
        this.lock = !this.lock;
        this.alpha = this.lock;
        this.shift = false;
        return 67;
      }
      this.alpha = this.lock ? false : !this.alpha;
      this.lock = false;
      return 13;
    }
    const page = this.alpha ? (this.shift ? 162 : 108) : this.shift ? 54 : 0;
    this.shift = false;
    if (!this.lock) this.alpha = false;
    return k < 12 ? k : k + page;
  }
}
